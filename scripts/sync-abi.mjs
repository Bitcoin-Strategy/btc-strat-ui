// Regenerates src/lib/abi/* from the compiled contracts.
//   node scripts/sync-abi.mjs [path-to-contracts-repo]
import fs from 'node:fs';
import path from 'node:path';

const repo = process.argv[2] ?? '../MSTRX';
const outDir = 'src/lib/abi';

const CONTRACTS = {
  'core/Treasury.sol/Treasury': 'treasury',
  'core/Bonding.sol/Bonding': 'bonding',
  'core/Redemption.sol/Redemption': 'redemption',
  'core/Staking.sol/Staking': 'staking',
  'core/VestingVault.sol/VestingVault': 'vesting',
  'core/PremiumSales.sol/PremiumSales': 'premium-sales',
  'core/FeeVault.sol/FeeVault': 'fee-vault',
  'tokens/STRAT.sol/STRAT': 'strat',
  'tokens/VVEST.sol/VVEST': 'vvest',
  'periphery/ProtocolReader.sol/ProtocolReader': 'protocol-reader',
  'governance/ProtocolAuthority.sol/ProtocolAuthority': 'authority',
  'governance/StratGovernor.sol/StratGovernor': 'governor',
  'governance/StratTimelock.sol/StratTimelock': 'timelock',
  'adapters/ProtocolOracle.sol/ProtocolOracle': 'protocol-oracle',
  'hooks/StratPoolHook.sol/StratPoolHook': 'pool-hook',
};

const constName = (file) =>
  `${file.replace(/-/g, '_').toUpperCase()}_ABI`;

let written = 0;
for (const [artifactPath, file] of Object.entries(CONTRACTS)) {
  const full = path.join(repo, 'artifacts/contracts', `${artifactPath}.json`);
  if (!fs.existsSync(full)) {
    console.error(`  MISSING  ${artifactPath}`);
    continue;
  }
  const { abi } = JSON.parse(fs.readFileSync(full, 'utf8'));
  const body = `/**
 * Generated from \`contracts/${artifactPath.split('/').slice(0, -1).join('/')}\` by
 * \`node scripts/sync-abi.mjs\`. Do not edit: re-run the script after a contract changes.
 */
export const ${constName(file)} = ${JSON.stringify(abi, null, 2)} as const;
`;
  fs.writeFileSync(path.join(outDir, `${file}.ts`), body);
  written += 1;
  console.log(`  ok  ${file}.ts  (${abi.length} entries)`);
}
console.log(`\n${written} ABIs written from ${repo}`);

// Reverts forwarded by ProtocolAuthority.execute arrive undecoded, so the app looks selectors up here.
import { toFunctionSelector } from 'viem';

const errorSelectors = {};
const seen = new Set();

const collectErrors = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      collectErrors(full);
      continue;
    }
    if (!entry.name.endsWith('.json') || entry.name.endsWith('.dbg.json')) continue;
    let artifact;
    try {
      artifact = JSON.parse(fs.readFileSync(full, 'utf8'));
    } catch {
      continue;
    }
    if (!Array.isArray(artifact.abi)) continue;
    for (const item of artifact.abi) {
      if (item.type !== 'error') continue;
      const signature = `${item.name}(${item.inputs.map((i) => i.type).join(',')})`;
      if (seen.has(signature)) continue;
      seen.add(signature);
      errorSelectors[toFunctionSelector(signature)] = item.name;
    }
  }
};

const artifactsRoot = path.join(repo, 'artifacts/contracts');
if (fs.existsSync(artifactsRoot)) {
  collectErrors(artifactsRoot);
  fs.writeFileSync(
    path.join(outDir, 'error-selectors.ts'),
    `/**
 * Every custom error the protocol's contracts declare, by selector.
 *
 * Generated by \`node scripts/sync-abi.mjs\`. Do not edit: re-run it after a contract changes.
 */
export const ERROR_SELECTORS: Record<string, string> = ${JSON.stringify(errorSelectors, null, 2)};
`,
  );
  console.log(`  ok  error-selectors.ts  (${Object.keys(errorSelectors).length} errors)`);
}
